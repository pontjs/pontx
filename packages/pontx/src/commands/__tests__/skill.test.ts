import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { skillCommand } from '../skill';
import * as fs from 'fs';
import * as path from 'path';

describe('skill command', () => {
  const testOutputPath = path.join(process.cwd(), '.claude-test-skill.md');

  afterEach(() => {
    // 清理测试文件
    if (fs.existsSync(testOutputPath)) {
      fs.unlinkSync(testOutputPath);
    }
  });

  it('should generate SKILL file with custom output path', async () => {
    await skillCommand({ output: testOutputPath });

    // 验证文件已生成
    expect(fs.existsSync(testOutputPath)).toBe(true);

    // 读取文件内容
    const content = fs.readFileSync(testOutputPath, 'utf-8');

    // 验证 YAML frontmatter
    expect(content).toContain('---');
    expect(content).toContain('name: pontx');
    expect(content).toContain('description: API lifecycle management');
    expect(content).toContain('tags:');
    expect(content).toContain('- api');
    expect(content).toContain('- openapi');

    // 验证核心章节
    expect(content).toContain('# Pontx AI Skill');
    expect(content).toContain('## Quick Start');
    expect(content).toContain('## Core Workflows');
    expect(content).toContain('### 1. Configure pontx.config.ts');
    expect(content).toContain('### 2. SDK Integration Workflow');
    expect(content).toContain('### 3. CLI Call Workflow');
    expect(content).toContain('### 4. CLI Commands Reference');
    expect(content).toContain('### 5. Build CLI Tool Workflow');
    expect(content).toContain('### 6. Shell Completion');
    expect(content).toContain('## Safety & Best Practices');
    expect(content).toContain('## Learn More');

    // 验证 CLI Call Workflow 包含安全警告
    expect(content).toContain('⚠️ **安全警告**');
    expect(content).toContain('--dry-run');
    expect(content).toContain('真实的副作用');

    // 验证区分 SDK 集成和 CLI 工具
    expect(content).toContain('在项目代码中集成 API');
    expect(content).toContain('构建独立的命令行工具');
    expect(content).toContain('import { userApi } from');
    expect(content).toContain('my-api-cli call');

    // 验证版本信息
    expect(content).toContain('Generated by `pontx skill`');
  });

  it('should print to stdout with --print option', async () => {
    // 捕获 console.log 输出
    const originalLog = console.log;
    let output = '';
    console.log = (msg: string) => {
      output += msg;
    };

    try {
      await skillCommand({ print: true });

      // 验证输出包含关键内容
      expect(output).toContain('name: pontx');
      expect(output).toContain('# Pontx AI Skill');
      expect(output).toContain('## Core Workflows');
    } finally {
      console.log = originalLog;
    }
  });
});
